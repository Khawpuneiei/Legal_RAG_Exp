import math

import pytest

from eval.generation_eval import align, resolve_id, score
from src.common import load_synthetic


@pytest.fixture(scope="module")
def lib():
    ds = load_synthetic()
    clauses = ds.meta["clauses"]
    by_key = {c["key"]: cid for cid, c in clauses.items()}
    return {q.qid: q for q in ds.queries}, clauses, by_key


def sel(requirement, clause_id=None, quote=""):
    return {"requirement": requirement, "clause_id": clause_id, "evidence_quote": quote}


def run(lib, qid, selections):
    qs, clauses, by_key = lib
    return score(qs[qid], selections, clauses, by_key, set())


def test_resolve_id_strips_copied_label_and_case():
    lookup = {"BP-DISPUTE-SG-COURTS": "BP-DISPUTE-SG-COURTS"}
    assert resolve_id("clause_id: BP-DISPUTE-SG-COURTS", lookup) == "BP-DISPUTE-SG-COURTS"
    assert resolve_id("[clause_id: bp-dispute-sg-courts]", lookup) == "BP-DISPUTE-SG-COURTS"
    assert resolve_id("null", lookup) is None and resolve_id(None, lookup) is None and resolve_id(" ", lookup) is None
    assert resolve_id("NDA-ONE-WILL-OBLIG", lookup) == "NDA-ONE-WILL-OBLIG"  # unknown ids stay as written


def test_label_prefixed_id_is_not_fabricated(lib):
    # REQ-073: side letter, asks = [courts], unsupported = [carbon_credits]
    m = run(lib, "REQ-073", [sel("Disputes should go to the Singapore courts", "clause_id: BP-DISPUTE-SG-COURTS")])
    assert m["hallucinated_rate"] == 0.0 and m["ask_recall"] == 1.0 and m["n_id_normalised"] == 1


def test_correct_abstention(lib):
    m = run(lib, "REQ-073", [sel("Disputes should go to the Singapore courts", "BP-DISPUTE-SG-COURTS"),
                             sel("Allocating carbon credits generated by portfolio companies to them")])
    assert m["missing_ask_outcomes"] == {"carbon_credits": "abstained"}
    assert m["correct_abstention"] == 1.0 and m["false_citation"] == 0.0


def test_false_citation_that_the_lenient_metric_misses(lib):
    # null on the supported ask, a citation on the unsupported one: the old item-level metric still scores 1
    m = run(lib, "REQ-073", [sel("No arbitration, Singapore courts"),
                             sel("Allocation of carbon credits to the investor", "SIDE-MFN")])
    assert m["abstention_lenient"] == 1.0
    assert m["false_citation"] == 1.0 and m["correct_abstention"] == 0.0


def test_omitted_unsupported_ask(lib):
    # REQ-096: side letter with only an unsupported ERISA ask
    m = run(lib, "REQ-096", [sel("Precedence of the side letter", "SIDE-PRECEDENCE")])
    assert m["missing_ask_outcomes"] == {"erisa": "omitted"} and m["missing_ask_omitted"] == 1.0


def test_one_to_one_alignment_ignores_a_weaker_second_match(lib):
    # "representation" alone links the second requirement to the ERISA phrasing; the closer null selection wins
    m = run(lib, "REQ-096", [sel("ERISA plan assets representation"),
                             sel("Institutional investor representation", "SUBS-INVESTOR-REPS-INSTITUTIONAL")])
    assert m["aligned_to"] == ["erisa", None] and m["correct_abstention"] == 1.0


def test_drafted_clause_is_not_an_abstention(lib):
    m = run(lib, "REQ-073", [sel("Carbon credit allocation", None, "All carbon credits generated by portfolio companies shall be allocated to the Investor.")])
    assert m["missing_ask_outcomes"] == {"carbon_credits": "drafted"} and m["correct_abstention"] == 0.0


def test_align_leaves_unrelated_requirements_unmatched():
    out = align(["Possible fund distribution arrangement", "Safekeeping of crypto tokens"], ["crypto_custody"])
    assert out[0][0] is None and out[1][0] == "crypto_custody"
    assert align([], ["crypto_custody"]) == [] and align(["x"], []) == [(None, 0.0)]


def test_requests_without_unsupported_asks_have_no_abstention_metrics(lib):
    qs, _, _ = lib
    qid = next(q for q, v in qs.items() if v.meta["split"] == "test" and not v.meta["missing_asks"])
    m = run(lib, qid, [sel("anything")])
    assert "correct_abstention" not in m and "abstention_lenient" not in m
    assert not math.isnan(m["hallucinated_rate"])
